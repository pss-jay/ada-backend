def _parse_version(version_str: str) -> tuple:
    """Parse 'v1.2' into (1, 2)."""
    v = version_str.lstrip("v")
    parts = v.split(".")
    try:
        return int(parts[0]), int(parts[1]) if len(parts) > 1 else 0
    except (ValueError, IndexError):
        return 0, 1


def _hash_json(data: dict) -> str:
    """Create a short content hash for change detection."""
    s = json.dumps(data, sort_keys=True, default=str)
    return hashlib.md5(s.encode()).hexdigest()[:12]


def _count_nonempty_fields(data: dict, depth: int = 0) -> int:
    """Count non-empty fields in a nested dict."""
    if depth > 10:
        return 0
    count = 0
    if isinstance(data, dict):
        for v in data.values():
            if isinstance(v, dict):
                count += _count_nonempty_fields(v, depth + 1)
            elif isinstance(v, list):
                count += len(v)
            elif v and str(v).strip() and str(v) not in ("None", "0", "[]", "{}"):
                count += 1
    return count


def _flatten_for_diff(data, prefix: str = "") -> dict:
    """Flatten a section to field-level key-value pairs for comparison."""
    result = {}
    if isinstance(data, dict):
        for k, v in data.items():
            key = f"{prefix}.{k}" if prefix else k
            if isinstance(v, dict):
                result.update(_flatten_for_diff(v, key))
            elif isinstance(v, list):
                result[key] = json.dumps(v, default=str)
            else:
                result[key] = str(v) if v is not None else ""
    elif isinstance(data, str):
        result[prefix] = data
    return result


def _summarize_section(section_data) -> str:
    """Create a brief text summary of a section for the diff display."""
    if isinstance(section_data, str):
        return section_data[:200]
    if isinstance(section_data, dict):
        parts = []
        for k, v in section_data.items():
            if v and str(v).strip() and str(v) not in ("None", "{}", "[]"):
                val = str(v)[:80]
                parts.append(f"{k}: {val}")
            if len(parts) >= 4:
                break
        return "; ".join(parts) if parts else "(empty section)"
    return str(section_data)[:200]


def _classify_severity(section_key: str, field_changes: list) -> str:
    """Classify change severity as 'substantive' or 'minor'.

    Substantive = changes that affect study design, animal counts, dosing,
    timelines, regulatory compliance, or cost.
    Minor = formatting, administrative, reporting adjustments.
    """
    substantive_sections = {
        "BasicDetails", "StudyInfo", "TestMaterial", "TestSystem",
        "ExperimentalDesign", "ExperimentalObservationsandProcedures",
        "LaboratoryAssessments", "TerminalProceduresandPathology",
        "RegulatoryCompliance", "Schedule",
    }

    substantive_fields = {
        "duration", "doselevels", "route", "species", "strain",
        "animals", "males", "females", "groups", "glp",
        "necropsy", "recovery", "sacrifice", "dose",
    }

    if section_key in substantive_sections:
        # Check if any field names relate to study-critical parameters
        for change in field_changes:
            field_lower = change["field"].lower()
            if any(sf in field_lower for sf in substantive_fields):
                return "substantive"
        # If 3+ fields changed in a substantive section, call it substantive
        if len(field_changes) >= 3:
            return "substantive"

    return "minor" if field_changes else "none"


def _describe_changes(section_key: str, field_changes: list) -> list:
    """Generate human-readable descriptions of field-level changes."""
    descriptions = []
    for change in field_changes[:8]:  # Cap at 8 descriptions
        field = change["field"].split(".")[-1]
        old = change["original"][:60] if change["original"] else "(empty)"
        new = change["amended"][:60] if change["amended"] else "(empty)"

        # Make human-friendly field name
        friendly = field.replace("_", " ").replace("And", " and ")
        # Add spaces before capitals (camelCase → sentence)
        import re
        friendly = re.sub(r'([a-z])([A-Z])', r'\1 \2', friendly)

        if not old or old == "(empty)":
            descriptions.append(f"{friendly} added: {new}")
        elif not new or new == "(empty)":
            descriptions.append(f"{friendly} removed (was: {old})")
        else:
            descriptions.append(f"{friendly} changed from \"{old}\" to \"{new}\"")

    if len(field_changes) > 8:
        descriptions.append(f"...and {len(field_changes) - 8} more field changes")

    return descriptions


