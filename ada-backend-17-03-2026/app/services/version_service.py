"""Version tracking, amendment management, audit log, and diff engine.

Data model (JSON file storage for Phase 1):

protocol_{id}.json  — main protocol record (unchanged from before)
versions_{id}.json  — version history for a protocol
amendments_{id}.json — amendments branched from a protocol
audit_{id}.json     — audit log entries

Version lifecycle:
  v0.1 (Draft, auto-generated by Ada)
  v0.2 (SD Review, Study Director edits)
  v0.3 (Sponsor Review, imported external edits)
  v1.0 (Finalized, signed off)

Amendment lifecycle:
  Amendment 1 → v0.1 ... v1.0 (finalized)
  Amendment 2 → v0.1 ... v1.0 (finalized)
  Each amendment is a branched copy with its own version history.
"""

