def _load_versions(protocol_id: str) -> List[dict]:
    return get_storage_backend().load_versions(protocol_id)

def _save_versions(protocol_id: str, versions: list):
    get_storage_backend().save_versions(protocol_id, versions)


def create_version(
    protocol_id: str,
    extracted_json: dict,
    author: str = "Ada (auto-generated)",
    label: str = "",
    status: str = "Draft",
    version_override: str = None,
) -> dict:
    """Create a new version snapshot of the protocol's extracted JSON.

    Returns the new version record.
    """
    versions = _load_versions(protocol_id)

    # Determine version number
    if version_override:
        version_num = version_override
    elif not versions:
        version_num = "v0.1"
    else:
        last = versions[-1]["version"]
        # Parse last version
        major, minor = _parse_version(last)
        if status.lower() in ("finalized", "ready for signature", "signed"):
            version_num = f"v{major + 1}.0"
        else:
            version_num = f"v{major}.{minor + 1}"

    # Compute content hash to detect actual changes
    content_hash = _hash_json(extracted_json)

    # Check if identical to last version (skip duplicate snapshots)
    if versions and versions[-1].get("content_hash") == content_hash:
        logger.info(f"Skipping duplicate version for {protocol_id} (content unchanged)")
        return versions[-1]

    version_record = {
        "version": version_num,
        "protocol_id": protocol_id,
        "timestamp": datetime.utcnow().isoformat() + "Z",
        "author": author,
        "label": label or f"Version {version_num}",
        "status": status,
        "content_hash": content_hash,
        "extracted_json": extracted_json,
        "field_count": _count_nonempty_fields(extracted_json),
    }

    versions.append(version_record)
    _save_versions(protocol_id, versions)

    # Log audit entry
    add_audit_entry(
        protocol_id=protocol_id,
        action="version_created",
        author=author,
        details={"version": version_num, "status": status, "field_count": version_record["field_count"]},
    )

    logger.info(f"Created version {version_num} for protocol {protocol_id} by {author}")
    return version_record


def get_versions(protocol_id: str) -> List[dict]:
    """Get all versions for a protocol (without full JSON to keep response small)."""
    versions = _load_versions(protocol_id)
    # Return summaries (exclude full extracted_json for list view)
    summaries = []
    for v in versions:
        summaries.append({
            "version": v["version"],
            "timestamp": v["timestamp"],
            "author": v["author"],
            "label": v["label"],
            "status": v["status"],
            "field_count": v.get("field_count", 0),
            "content_hash": v.get("content_hash", ""),
        })
    return summaries


def get_version_detail(protocol_id: str, version_num: str) -> Optional[dict]:
    """Get a specific version with full extracted JSON."""
    versions = _load_versions(protocol_id)
    for v in versions:
        if v["version"] == version_num:
            return v
    return None


def update_version_status(protocol_id: str, version_num: str, new_status: str, author: str = "System") -> Optional[dict]:
    """Update the status of a specific version."""
    versions = _load_versions(protocol_id)
    for v in versions:
        if v["version"] == version_num:
            old_status = v["status"]
            v["status"] = new_status
            _save_versions(protocol_id, versions)
            add_audit_entry(
                protocol_id=protocol_id,
                action="version_status_changed",
                author=author,
                details={"version": version_num, "old_status": old_status, "new_status": new_status},
            )
            return v
    return None


