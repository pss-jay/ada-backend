def compute_diff(original_json: dict, amended_json: dict) -> List[dict]:
    """Compute a section-by-section diff between two protocol JSONs.

    Returns a list of diff sections in the format expected by the frontend:
    {
        section: "Study Information",
        id: "study-info",
        type: "modified" | "unchanged" | "added" | "removed",
        severity: "substantive" | "minor" | "none",
        original: "summary of original values",
        amended: "summary of amended values",
        changes: ["list of specific changes"],
        impact: "downstream impact description",
        field_details: [{field, old, new}]
    }
    """
    diff_sections = []

    # Get all top-level keys from both
    all_keys = set(list(original_json.keys()) + list(amended_json.keys()))

    for section_key in PROTOCOL_SECTIONS:
        if section_key not in all_keys:
            continue

        orig_section = original_json.get(section_key, {})
        amend_section = amended_json.get(section_key, {})

        display_name = SECTION_DISPLAY_NAMES.get(section_key, section_key)
        section_id = section_key.lower().replace(" ", "-")

        # Flatten both sections for field-by-field comparison
        orig_flat = _flatten_for_diff(orig_section, section_key)
        amend_flat = _flatten_for_diff(amend_section, section_key)

        all_fields = set(list(orig_flat.keys()) + list(amend_flat.keys()))

        field_changes = []
        for field in sorted(all_fields):
            orig_val = str(orig_flat.get(field, "")).strip()
            amend_val = str(amend_flat.get(field, "")).strip()

            if orig_val != amend_val:
                # Skip empty-to-empty changes
                if not orig_val and not amend_val:
                    continue
                field_changes.append({
                    "field": field,
                    "original": orig_val,
                    "amended": amend_val,
                })

        if not field_changes:
            # Section unchanged
            orig_summary = _summarize_section(orig_section)
            diff_sections.append({
                "section": display_name,
                "id": section_id,
                "type": "unchanged",
                "severity": "none",
                "original": orig_summary,
                "amended": orig_summary,
                "changes": [],
                "impact": "",
                "costImpact": "",
                "field_details": [],
            })
        else:
            # Determine severity based on number and nature of changes
            severity = _classify_severity(section_key, field_changes)
            change_descriptions = _describe_changes(section_key, field_changes)
            impact = _assess_impact(section_key, field_changes)

            diff_sections.append({
                "section": display_name,
                "id": section_id,
                "type": "modified",
                "severity": severity,
                "original": _summarize_section(orig_section),
                "amended": _summarize_section(amend_section),
                "changes": change_descriptions,
                "impact": impact,
                "costImpact": "",  # Phase 2: cost estimation
                "field_details": field_changes,
            })

    # Also check for sections only in amended (added)
    for key in amended_json:
        if key not in original_json and key in SECTION_DISPLAY_NAMES:
            diff_sections.append({
                "section": SECTION_DISPLAY_NAMES.get(key, key),
                "id": key.lower(),
                "type": "added",
                "severity": "substantive",
                "original": "",
                "amended": _summarize_section(amended_json[key]),
                "changes": [f"New section added: {SECTION_DISPLAY_NAMES.get(key, key)}"],
                "impact": "New section requires full review.",
                "costImpact": "",
                "field_details": [],
            })

    return diff_sections


def compare_versions(protocol_id: str, version_a: str, version_b: str) -> dict:
    """Compare two versions of a protocol and return the diff report.

    Returns the full comparison data expected by the frontend's
    renderAmendmentReport() function.
    """
    va = get_version_detail(protocol_id, version_a)
    vb = get_version_detail(protocol_id, version_b)

    if not va:
        raise ValueError(f"Version {version_a} not found for protocol {protocol_id}")
    if not vb:
        raise ValueError(f"Version {version_b} not found for protocol {protocol_id}")

    diff_sections = compute_diff(va["extracted_json"], vb["extracted_json"])

    modified = [d for d in diff_sections if d["type"] == "modified"]
    substantive = [d for d in modified if d["severity"] == "substantive"]
    minor = [d for d in modified if d["severity"] == "minor"]
    unchanged = [d for d in diff_sections if d["type"] == "unchanged"]

    return {
        "protocol_id": protocol_id,
        "version_a": version_a,
        "version_b": version_b,
        "timestamp_a": va["timestamp"],
        "timestamp_b": vb["timestamp"],
        "summary": {
            "total_sections": len(diff_sections),
            "modified_count": len(modified),
            "substantive_count": len(substantive),
            "minor_count": len(minor),
            "unchanged_count": len(unchanged),
        },
        "diff_sections": diff_sections,
    }


def compare_amendment(protocol_id: str, amendment_number: int) -> dict:
    """Compare an amendment against its base protocol version.

    Retrieves the amendment's current JSON and the base protocol version,
    then computes the diff.
    """
    amendment = get_amendment_detail(protocol_id, amendment_number)
    if not amendment:
        raise ValueError(f"Amendment {amendment_number} not found")

    base_version = amendment.get("base_version", "v0.1")
    base = get_version_detail(protocol_id, base_version)

    if not base:
        # Try to use the first version
        versions = _load_versions(protocol_id)
        base = versions[0] if versions else None

    if not base:
        raise ValueError(f"Base version not found for comparison")

    diff_sections = compute_diff(base["extracted_json"], amendment["extracted_json"])

    modified = [d for d in diff_sections if d["type"] in ("modified", "added")]
    substantive = [d for d in modified if d["severity"] == "substantive"]
    minor = [d for d in modified if d["severity"] == "minor"]

    return {
        "protocol_id": protocol_id,
        "amendment_number": amendment_number,
        "amendment_version": amendment["current_version"],
        "base_version": base_version,
        "summary": {
            "total_sections": len(diff_sections),
            "modified_count": len(modified),
            "substantive_count": len(substantive),
            "minor_count": len(minor),
        },
        "diff_sections": diff_sections,
        "changes_summary": amendment.get("changes_summary", []),
    }


