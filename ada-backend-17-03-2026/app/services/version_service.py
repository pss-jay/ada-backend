def create_amendment(
    protocol_id: str,
    base_version: str = None,
    author: str = "Study Director",
    reason: str = "",
) -> dict:
    """Create a new amendment branched from a protocol version.

    An amendment gets its own version history (v0.1, v0.2... until finalized).
    Returns the amendment record.
    """
    amendments = _load_amendments(protocol_id)

    # Determine amendment number
    amendment_num = len(amendments) + 1
    amendment_id = f"{protocol_id}-amend-{amendment_num}"

    # Get the base version's extracted JSON
    if base_version:
        base = get_version_detail(protocol_id, base_version)
    else:
        # Use the latest version
        versions = _load_versions(protocol_id)
        base = versions[-1] if versions else None

    if not base:
        raise ValueError(f"No base version found for protocol {protocol_id}")

    base_json = copy.deepcopy(base.get("extracted_json", {}))

    amendment_record = {
        "amendment_id": amendment_id,
        "amendment_number": amendment_num,
        "protocol_id": protocol_id,
        "base_version": base.get("version", "v0.1"),
        "created_at": datetime.utcnow().isoformat() + "Z",
        "author": author,
        "reason": reason,
        "status": "In Progress",
        "current_version": "v0.1",
        "extracted_json": base_json,  # Starts as a copy of the base
        "changes_summary": [],  # Will be populated as edits are made
    }

    amendments.append(amendment_record)
    _save_amendments(protocol_id, amendments)

    # Also create a v0.1 in the amendment's own version history
    _save_versions(amendment_id, [{
        "version": "v0.1",
        "protocol_id": amendment_id,
        "timestamp": datetime.utcnow().isoformat() + "Z",
        "author": author,
        "label": f"Amendment {amendment_num} - Initial Draft",
        "status": "Draft",
        "content_hash": _hash_json(base_json),
        "extracted_json": base_json,
        "field_count": _count_nonempty_fields(base_json),
    }])

    add_audit_entry(
        protocol_id=protocol_id,
        action="amendment_created",
        author=author,
        details={
            "amendment_id": amendment_id,
            "amendment_number": amendment_num,
            "base_version": base.get("version", "v0.1"),
            "reason": reason,
        },
    )

    logger.info(f"Created Amendment {amendment_num} for protocol {protocol_id}")
    return amendment_record


def get_amendments(protocol_id: str) -> List[dict]:
    """Get all amendments for a protocol (summaries)."""
    amendments = _load_amendments(protocol_id)
    summaries = []
    for a in amendments:
        summaries.append({
            "amendment_id": a["amendment_id"],
            "amendment_number": a["amendment_number"],
            "base_version": a["base_version"],
            "created_at": a["created_at"],
            "author": a["author"],
            "reason": a.get("reason", ""),
            "status": a["status"],
            "current_version": a["current_version"],
            "changes_count": len(a.get("changes_summary", [])),
        })
    return summaries


def get_amendment_detail(protocol_id: str, amendment_number: int) -> Optional[dict]:
    """Get a specific amendment with full data."""
    amendments = _load_amendments(protocol_id)
    for a in amendments:
        if a["amendment_number"] == amendment_number:
            return a
    return None


def update_amendment(
    protocol_id: str,
    amendment_number: int,
    sections: dict,
    author: str = "Study Director",
) -> dict:
    """Update fields in an amendment's extracted JSON.

    Tracks each change in the changes_summary list.
    Returns the updated amendment.
    """
    amendments = _load_amendments(protocol_id)
    target = None
    for a in amendments:
        if a["amendment_number"] == amendment_number:
            target = a
            break

    if not target:
        raise ValueError(f"Amendment {amendment_number} not found for protocol {protocol_id}")

    extracted = target.get("extracted_json", {})
    changes_made = []

    for key, new_value in sections.items():
        parts = key.split(".")
        obj = extracted
        old_value = None

        # Navigate to parent
        for part in parts[:-1]:
            if isinstance(obj, dict) and part in obj:
                obj = obj[part]
            else:
                obj = None
                break

        if obj is not None and isinstance(obj, dict):
            field_name = parts[-1]
            old_value = obj.get(field_name)
            obj[field_name] = new_value

            if str(old_value) != str(new_value):
                changes_made.append({
                    "field": key,
                    "old_value": str(old_value) if old_value else "",
                    "new_value": str(new_value),
                    "timestamp": datetime.utcnow().isoformat() + "Z",
                    "author": author,
                })

    target["extracted_json"] = extracted
    target["changes_summary"].extend(changes_made)

    # Bump amendment version
    old_ver = target["current_version"]
    major, minor = _parse_version(old_ver)
    target["current_version"] = f"v{major}.{minor + 1}"

    _save_amendments(protocol_id, amendments)

    # Save a version snapshot for the amendment
    amendment_id = target["amendment_id"]
    create_version(
        protocol_id=amendment_id,
        extracted_json=extracted,
        author=author,
        label=f"Amendment {amendment_number} - {target['current_version']}",
        status="In Progress",
    )

    # Audit
    add_audit_entry(
        protocol_id=protocol_id,
        action="amendment_edited",
        author=author,
        details={
            "amendment_number": amendment_number,
            "fields_changed": len(changes_made),
            "version": target["current_version"],
        },
    )

    return {
        "amendment_number": amendment_number,
        "current_version": target["current_version"],
        "fields_changed": len(changes_made),
        "changes": changes_made,
    }


def finalize_amendment(
    protocol_id: str,
    amendment_number: int,
    author: str = "Study Director",
) -> dict:
    """Finalize an amendment: mark it finalized and merge into main version history."""
    amendments = _load_amendments(protocol_id)
    for a in amendments:
        if a["amendment_number"] == amendment_number:
            a["status"] = "Finalized"
            major, minor = _parse_version(a["current_version"])
            final_version = f"v{major + 1}.0"
            a["current_version"] = final_version
            _save_amendments(protocol_id, amendments)

            # Merge amendment data into main version history
            amended_json = a.get("extracted_json", {})
            if amended_json:
                create_version(
                    protocol_id=protocol_id,
                    extracted_json=amended_json,
                    author=author,
                    label=f"Amendment {amendment_number} finalized",
                    status="Approved",
                    version_override=final_version,
                )

                # Also update the main protocol data via storage backend
                storage = get_storage_backend()
                protocol = storage.load_protocol(protocol_id)
                if protocol:
                    protocol["extracted_json"] = amended_json
                    protocol["status"] = "amended"
                    storage.save_protocol(protocol_id, protocol)

            add_audit_entry(
                protocol_id=protocol_id,
                action="amendment_finalized",
                author=author,
                details={
                    "amendment_number": amendment_number,
                    "final_version": final_version,
                    "merged_to_main": True,
                },
            )
            return {"amendment_number": amendment_number, "status": "Finalized", "version": final_version}
    raise ValueError(f"Amendment {amendment_number} not found")


